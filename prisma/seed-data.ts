// Example trips for development and demos. Prices are realistic estimates,
// not quotes. Confirmation codes are made up.
//
// Day numbers are offsets from the trip's start date (day 0 = startDate).
// Items go under the stop you are *at* (or leaving, for onward transport).

import type { ItemCategory, ItemStatus, LinkKind, TripType, Visibility } from "../src/generated/prisma/enums";

export type SeedLink = { kind: LinkKind; url: string; label?: string };

export type SeedItem = {
  category: ItemCategory;
  title: string;
  provider?: string;
  /** [day, "HH:MM"]; omit the time for an all-day item */
  start?: [number, string?];
  end?: [number, string?];
  from?: string;
  to?: string;
  cost?: number;
  status: ItemStatus;
  confirmationCode?: string;
  notes?: string;
  privateNotes?: string;
  links?: SeedLink[];
};

export type SeedStop = {
  name: string;
  region?: string;
  country: string;
  countryCode: string;
  lat: number;
  lng: number;
  /** [arrive day, depart day] */
  days: [number, number];
  notes?: string;
  items?: SeedItem[];
};

export type SeedTrip = {
  ownerEmail: string;
  coverImageUrl?: string;
  /** Fixed slug suffix so demo share links survive re-seeding */
  slugSuffix: string;
  title: string;
  type: TripType;
  visibility: Visibility;
  description: string;
  startDate: string;
  endDate: string;
  currency: string;
  budget?: number;
  travellers: number;
  stops: SeedStop[];
  /** Trip-wide items not tied to a stop (insurance, passes, gear) */
  items?: SeedItem[];
};

export type SeedUser = { name: string; email: string; homeCurrency: string };

/** Password for every demo account. Demo data only; never reuse it anywhere real. */
export const DEMO_PASSWORD = "tripstack-demo";

const booking = (url: string, label?: string): SeedLink => ({ kind: "BOOKING", url, label });
const confirmation = (url: string, label = "My booking"): SeedLink => ({ kind: "CONFIRMATION", url, label });
const info = (url: string, label?: string): SeedLink => ({ kind: "INFO", url, label });
// Cover photos from Unsplash (free Unsplash License), served by their CDN.
const unsplash = (photoId: string) =>
  `https://images.unsplash.com/${photoId}?auto=format&fit=crop&w=1200&q=70`;

const map = (lat: number, lng: number, label = "Map"): SeedLink => ({
  kind: "MAP",
  url: `https://www.openstreetmap.org/?mlat=${lat}&mlon=${lng}#map=16/${lat}/${lng}`,
  label,
});

